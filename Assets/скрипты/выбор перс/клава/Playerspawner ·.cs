public class PlayerSpawner : MonoBehaviour
{
    [Header("--- ????? ?????? ---")]
    [Tooltip("?????? GameObject — ??? ???????? ????? 1 (???????? ????? ?? ?????)")]
    public Transform player1SpawnPoint;

    [Tooltip("?????? GameObject — ??? ???????? ????? 2 (???????? ?????? ?? ?????)")]
    public Transform player2SpawnPoint;

    [Header("--- ???????? ??????? ---")]
    [Tooltip("???? GameData ??????-?? ?????? (???????? ????????? ????? ???????? ?? ????????? ??? ?????), ?????????? ??? ???????")]
    public GameObject fallbackPlayer1Prefab;
    public GameObject fallbackPlayer2Prefab;

    // ?????? ?? ???????????? ??????? — ????? ??????????? ?????? ????????
    [HideInInspector] public GameObject player1Instance;
    [HideInInspector] public GameObject player2Instance;

    void Start()
    {
        SpawnPlayer1();
        SpawnPlayer2();
    }

    void SpawnPlayer1()
    {
        GameObject prefab = GameData1.Player1CharacterPrefab1 != null
            ? GameData1.Player1CharacterPrefab1
            : fallbackPlayer1Prefab;

        if (prefab == null)
        {
            Debug.LogError("PlayerSpawner: ??? ??????? ??? ?????? 1! ??????? ????? ????????? ??? fallbackPlayer1Prefab.");
            return;
        }

        Vector3 pos = player1SpawnPoint != null ? player1SpawnPoint.position : Vector3.zero;
        Quaternion rot = player1SpawnPoint != null ? player1SpawnPoint.rotation : Quaternion.identity;

        player1Instance = Instantiate(prefab, pos, rot);
        player1Instance.name = "Player1_" + (GameData.Player1CharacterName ?? prefab.name);

        Debug.Log("????????? ????? 1: " + player1Instance.name);
    }

    void SpawnPlayer2()
    {
        GameObject prefab = GameData1.Player2CharacterPrefab1 != null
            ? GameData1.Player2CharacterPrefab1
            : fallbackPlayer2Prefab;

        if (prefab == null)
        {
            Debug.LogError("PlayerSpawner: ??? ??????? ??? ?????? 2! ??????? ????? ????????? ??? fallbackPlayer2Prefab.");
            return;
        }

        Vector3 pos = player2SpawnPoint != null ? player2SpawnPoint.position : Vector3.zero;
        Quaternion rot = player2SpawnPoint != null ? player2SpawnPoint.rotation : Quaternion.identity;

        player2Instance = Instantiate(prefab, pos, rot);
        player2Instance.name = "Player2_" + (GameData.Player2CharacterName ?? prefab.name);

        Debug.Log("????????? ????? 2: " + player2Instance.name);
    }
}